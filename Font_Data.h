String convertVietnamese(String s)
{
    s.replace("aaf", String((char)7)); // ầ
    s.replace("aaj", String((char)8)); // ậ
    s.replace("aar", String((char)9)); // ẩ
    s.replace("aas", String((char)10)); // ấ
    s.replace("aax", String((char)11)); // ẫ

// ă
    s.replace("awf", String((char)13)); // ằ
    s.replace("awj", String((char)14)); // ặ
    s.replace("awr", String((char)15)); // ẳ
    s.replace("aws", String((char)16)); // ắ
    s.replace("awx", String((char)17)); // ẵ

// ê
    s.replace("eef", String((char)25)); // ề
    s.replace("eej", String((char)26)); // ệ
    s.replace("eer", String((char)27)); // ể
    s.replace("ees", String((char)28)); // ế
    s.replace("eex", String((char)29)); // ễ

// ô
    s.replace("oof", String((char)145)); // ồ
    s.replace("ooj", String((char)149)); // ộ
    s.replace("oor", String((char)147)); // ổ
    s.replace("oos", String((char)146)); // ố
    s.replace("oox", String((char)148)); // ỗ

// ơ
    s.replace("owf", String((char)140)); // ờ
    s.replace("owj", String((char)144)); // ợ
    s.replace("owr", String((char)143)); // ở
    s.replace("ows", String((char)141)); // ớ
    s.replace("owx", String((char)142)); // ỡ

// ư
    s.replace("uwf", String((char)152)); // ừ
    s.replace("uwj", String((char)155)); // ự
    s.replace("uwr", String((char)154)); // ử
    s.replace("uws", String((char)151)); // ứ
    s.replace("uwx", String((char)153)); // ữ

// ===== 2 ký tự =====

// a
    s.replace("af", String((char)1)); // à
    s.replace("aj", String((char)2)); // ạ
    s.replace("ar", String((char)3)); // ả
    s.replace("as", String((char)4)); // á
    s.replace("ax", String((char)5)); // ã

// â
    s.replace("aa", String((char)6)); // â

// ă
    s.replace("aw", String((char)12)); // ă

// đ
    s.replace("dd", String((char)18)); // đ

// e
    s.replace("ef", String((char)20)); // è
    s.replace("ej", String((char)21)); // ẹ
    s.replace("er", String((char)22)); // ẻ
    s.replace("es", String((char)23)); // é
    s.replace("ex", String((char)24)); // ẽ

// ê
    s.replace("ee", String((char)19)); // ê

// i
    s.replace("if", String((char)128)); // ì
    s.replace("ij", String((char)129)); // ị
    s.replace("ir", String((char)130)); // ỉ
    s.replace("is", String((char)131)); // í
    s.replace("ix", String((char)132)); // ĩ

// o
    s.replace("of", String((char)134)); // ò
    s.replace("oj", String((char)137)); // ọ
    s.replace("or", String((char)136)); // ỏ
    s.replace("os", String((char)135)); // ó
    s.replace("ox", String((char)138)); // õ

// ô
    s.replace("oo", String((char)133)); // ô

// ơ
    s.replace("ow", String((char)139)); // ơ

// u
    s.replace("uf", String((char)157)); // ù
    s.replace("uj", String((char)160)); // ụ
    s.replace("ur", String((char)158)); // ủ
    s.replace("us", String((char)156)); // ú
    s.replace("ux", String((char)159)); // ũ

// ư
    s.replace("uw", String((char)150)); // ư

// y
    s.replace("yf", String((char)162)); // ỳ
    s.replace("yj", String((char)166)); // ỵ
    s.replace("yr", String((char)164)); // ỷ
    s.replace("ys", String((char)163)); // ý
    s.replace("yx", String((char)165)); // ỹ
    return s;
}
